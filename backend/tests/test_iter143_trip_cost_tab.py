# ── Helpers ────────────────────────────────────────────────────────────────

def _customer():
    r = requests.get(f"{API}/customers", headers=H, timeout=15)
    for c in r.json():
        if c["name"] == "TEST_Iter143":
            return c["id"]
    return requests.post(
        f"{API}/customers", headers=H,
        json={"name": "TEST_Iter143", "state": "Andhra Pradesh"}, timeout=15,
    ).json()["id"]


def _first_own_vehicle():
    lst = requests.get(f"{API}/vehicles", headers=H, params={"active_only": True}, timeout=15).json()
    for v in lst:
        if (v.get("vehicle_type") or "").lower() != "supplier":
            return v
    return lst[0]


def _first_supplier_vehicle():
    lst = requests.get(f"{API}/vehicles", headers=H, params={"active_only": True}, timeout=15).json()
    for v in lst:
        if (v.get("vehicle_type") or "").lower() == "supplier":
            return v
    return None


