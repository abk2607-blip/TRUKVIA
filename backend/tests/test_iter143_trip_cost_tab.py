"""Iter143 P1 · Vehicle Workspace · Trip Cost tab — regression tests.

The Trip Cost tab is a PURE projection of:
  * GET /api/vehicles/{vid}/cost-summary  (authoritative cost source)
  * GET /api/trips?vehicle_id=vid          (metadata join)

Zero new backend endpoint. Zero schema change. Zero new collection.
Zero recalculation from Trip.total_expense / VendorBill / MechanicWO /
supplier payable.

Every assertion below mirrors an invariant the frontend depends on:

  1.  cost-summary row shape stable (trip_id, category, amount, source_type)
  2.  legacy XOR fallback rows still tagged & carry trip_id
  3.  supplier_freight / advance / diesel / net_payable NEVER appear in rows[]
  4.  supplier trip cost rows are visible with correct vehicle_id / vehicle_type
  5.  cancelled Quick Op vanishes from rows[]
  6.  reversed Expense excluded from rows[]
  7.  a zero-cost trip is invisible on the tab (no row generated by the FE)
  8.  cross-vehicle isolation (no leak)
  9.  date/category filter parity: cost-summary filter response == what the tab consumes
 10. sum of grouped trip totals == cost-summary.trip_linked_total
 11. trip_linked_total + non_trip_total == total_cost
 12. legacy → canonical materialisation preserves the same trip total
 13. non-trip Expense (trip_id="") never lands in any trip group

Frontend static guards confirm the tab is wired with the expected testids
and does NOT read from any of the forbidden legacy scalars.
"""
from pathlib import Path
import os
import uuid
import requests

BASE_URL = os.environ.get("REACT_APP_BACKEND_URL", "http://localhost:8001").rstrip("/")
API = f"{BASE_URL}/api"
if not API.startswith("http"):
    API = "http://localhost:8001/api"
TOKEN = os.environ.get("DEMO_TOKEN_VALUE", "")
