@router.post("/drivers/{did}/ledger/post-monthly-salary")
async def post_monthly_salary(did: str, payload: PostMonthlySalaryIn, request: Request,
                               user=Depends(get_current_user)):
    """Generate the monthly salary credit for the given month.
    Idempotent — re-posting the same month updates the amount to the
    current salary master value.  Historic months keep the salary that
    was effective THEN (via resolve_salary_master_for_month).
    """
    cid = await _active_company_id(request, user)
    drv = await _assert_driver(user["user_id"], cid, did)
    month = payload.month
    if len(month) != 7 or month[4] != "-":
        raise HTTPException(status_code=400, detail="month must be YYYY-MM")
    master = await _resolve_salary_master_for_month(user["user_id"], cid, did, month)
    if not master:
        raise HTTPException(status_code=400, detail="No salary master effective for this month")
    from calendar import monthrange
    y, m = int(month[:4]), int(month[5:7])
    last_day = f"{month}-{monthrange(y, m)[1]:02d}"
    now = datetime.now(timezone.utc).isoformat()
    existing = await db.driver_ledger_entries.find_one({
        "user_id": user["user_id"], "company_id": cid, "driver_id": did,
        "entry_type": "salary", "source": "system",
        "reference.kind": "salary_master", "reference.month": month,
    })
    doc = {
        "user_id": user["user_id"], "company_id": cid, "driver_id": did,
        "entry_date": last_day,
        "month_key": month,
        "entry_type": "salary",
        "direction": "credit",
        "amount": round(float(master["monthly_salary"]), 2),
        "source": "system",
        "reference": {"kind": "salary_master", "id": master["id"], "month": month,
                       "version": master.get("version", 1)},
        "remarks": f"Monthly salary — {month}",
        "updated_at": now, "updated_by": user["user_id"],
    }
    if existing:
        await db.driver_ledger_entries.update_one({"_id": existing["_id"]}, {"$set": doc})
        eid = existing["id"]
    else:
        eid = new_id("dle")
        doc.update({"id": eid, "created_at": now, "created_by": user["user_id"]})
        await db.driver_ledger_entries.insert_one(doc)
    doc.pop("_id", None); doc.pop("user_id", None)
    await _log_audit(user, "driver_ledger", "post_monthly_salary", entity_id=eid, entity_ref=did,
                     changes={"month": month, "amount": doc["amount"]})
    return {**doc, "id": eid, "posted": not bool(existing), "updated": bool(existing)}


