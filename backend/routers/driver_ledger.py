"""Iter61 · Phase C — Driver Salary & Payment Ledger.

Two collections:
  * driver_salary_masters  — effective-dated salary versions per driver
  * driver_ledger_entries  — the immutable transaction log:
      credit  = amount OWED to driver (salary earned)
      debit   = amount PAID / DEDUCTED (advance, trip recovery, settlement)
    Balance = Σ(credit) − Σ(debit).  Positive => we still owe the driver.

Entry types  (kept as a bounded whitelist for reporting integrity):
   salary            — credit; auto-generated by post-monthly-salary
   advance           — debit ; salary advance paid mid-month
   other_payment     — debit ; any other outflow to driver
   trip_recovery     — debit ; auto-mirrored from Trip driver_recovery
   other_deduction   — debit ; manual deduction (uniform, damages, ...)
   settlement        — debit ; monthly close-out payment

Every row is scoped by (user_id, company_id, driver_id) so multi-company
isolation is enforced by construction.  Trip-linked rows carry
`reference = {"kind":"trip","id":<tid>}` so we can idempotently upsert /
delete when Trips change (Trip = single source of truth).
"""
