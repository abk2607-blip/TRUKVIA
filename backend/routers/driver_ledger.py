# Trip → Ledger Sync (called from routers/trips.py)
# ===========================================================================
async def sync_trip_recovery_to_ledger(user_id: str, cid: str, trip: dict) -> None:
    """Upsert a trip_recovery ledger entry mirroring the Trip's
    driver_recovery.final_recovery_amount.  Called on Trip create + update.

    Idempotent — reference={kind:'trip', id:tid} is the natural key.
    If recovery ≤ 0 (or no driver / no snapshot), any prior entry is
    removed (Trip is the single source of truth).
    """
    tid = trip.get("id")
    did = trip.get("driver_id")
    dr = trip.get("driver_recovery") or {}
    amount = float(dr.get("final_recovery_amount") or 0)
    key = {"user_id": user_id, "company_id": cid,
           "entry_type": "trip_recovery", "source": "system",
           "reference.kind": "trip", "reference.id": tid}
    if not did or amount <= 0:
        # Remove any orphaned entry (e.g. driver reassigned, override reduced to 0)
        await db.driver_ledger_entries.delete_many(key)
        return
    now = datetime.now(timezone.utc).isoformat()
    entry_date = trip.get("date") or datetime.now(timezone.utc).date().isoformat()
    doc = {
        "user_id": user_id, "company_id": cid, "driver_id": did,
        "entry_date": entry_date,
        "month_key": _month_key(entry_date),
        "entry_type": "trip_recovery",
        "direction": "debit",
        "amount": round(amount, 2),
        "source": "system",
        "reference": {
            "kind": "trip", "id": tid,
            "lr_number": trip.get("lr_number") or "",
            "vehicle_number": trip.get("vehicle_number") or "",
        },
        "remarks": f"Trip recovery — LR {trip.get('lr_number') or tid[:8]}",
        "updated_at": now,
    }
    existing = await db.driver_ledger_entries.find_one(key)
    if existing:
        # Preserve driver_id changes too — if driver reassigned, we must
        # remove the OLD driver's entry and insert a fresh one under the
        # new driver.
        if existing.get("driver_id") != did:
            await db.driver_ledger_entries.delete_one({"_id": existing["_id"]})
        else:
            await db.driver_ledger_entries.update_one({"_id": existing["_id"]}, {"$set": doc})
            return
    doc.update({"id": new_id("dle"), "created_at": now})
    await db.driver_ledger_entries.insert_one(doc)


async def delete_trip_recovery_from_ledger(user_id: str, cid: str, trip_id: str) -> None:
    """Delete the ledger entry linked to a Trip when the Trip is deleted."""
    await db.driver_ledger_entries.delete_many({
        "user_id": user_id, "company_id": cid,
        "entry_type": "trip_recovery", "source": "system",
        "reference.kind": "trip", "reference.id": trip_id,
    })


