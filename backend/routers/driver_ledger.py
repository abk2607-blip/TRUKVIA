@router.post("/drivers/{did}/salary-masters")
async def create_salary_master(did: str, payload: SalaryMasterIn, request: Request,
                                user=Depends(get_current_user)):
    """Create a new effective-dated salary record.

    Historical records are NEVER edited — creating a new record with a
    later effective_from date supersedes prior salary starting from that
    date.  Prior record's `effective_to` is auto-set to
    (new.effective_from - 1 day) IF it was open-ended.
    """
    cid = await _active_company_id(request, user)
    await _assert_driver(user["user_id"], cid, did)
    now = datetime.now(timezone.utc).isoformat()
    # Close out any open-ended prior salary that overlaps
    prior = await db.driver_salary_masters.find_one(
        {"user_id": user["user_id"], "company_id": cid, "driver_id": did,
         "$or": [{"effective_to": None}, {"effective_to": {"$exists": False}}],
         "effective_from": {"$lt": payload.effective_from}},
        sort=[("effective_from", -1)],
    )
    if prior:
        # yesterday of new.effective_from
        try:
            y = datetime.strptime(payload.effective_from, "%Y-%m-%d").date()
            eff_to = (y.replace(day=y.day)).isoformat() if y.day == 1 else ""
            from datetime import timedelta as _td
            eff_to = (y - _td(days=1)).isoformat()
        except Exception:
            eff_to = payload.effective_from
        await db.driver_salary_masters.update_one(
            {"id": prior["id"]},
            {"$set": {"effective_to": eff_to, "updated_at": now, "updated_by": user["user_id"]}},
        )
    # Version = count of prior records + 1
    prev_count = await db.driver_salary_masters.count_documents(
        {"user_id": user["user_id"], "company_id": cid, "driver_id": did}
    )
    doc = {
        "id": new_id("dsm"),
        "user_id": user["user_id"], "company_id": cid, "driver_id": did,
        "version": prev_count + 1,
        "monthly_salary": float(payload.monthly_salary),
        "effective_from": payload.effective_from,
        "effective_to": payload.effective_to or None,
        "remarks": (payload.remarks or "").strip() or None,
        "created_at": now, "created_by": user["user_id"],
        "updated_at": now, "updated_by": user["user_id"],
    }
    await db.driver_salary_masters.insert_one(doc)
    doc.pop("_id", None)
    await _log_audit(user, "driver_salary_master", "create", entity_id=doc["id"], entity_ref=did)
    return doc


async def _resolve_salary_master_for_month(user_id: str, cid: str, did: str, month: str) -> Optional[dict]:
    """Return the salary master that applies to the last day of `month`
    (YYYY-MM).  Used by monthly-salary posting."""
    # Compute the last date of the month
    from calendar import monthrange
    y, m = int(month[:4]), int(month[5:7])
    last_day = f"{month}-{monthrange(y, m)[1]:02d}"
    p = await db.driver_salary_masters.find_one(
        {"user_id": user_id, "company_id": cid, "driver_id": did,
         "effective_from": {"$lte": last_day},
         "$or": [
             {"effective_to": {"$exists": False}},
             {"effective_to": None},
             {"effective_to": {"$gte": last_day}},
         ]},
        sort=[("effective_from", -1), ("version", -1)],
    )
    if p:
        p.pop("_id", None)
    return p


